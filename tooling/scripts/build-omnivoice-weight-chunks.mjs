import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { open, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { OMNIVOICE_DATA } from '../../src/tts/omnivoice/model-data.js';

assert(process.argv.slice(2).every(arg => arg === '--check'), 'Usage: node tooling/scripts/build-omnivoice-weight-chunks.mjs [--check]');
const root = path.resolve(import.meta.dirname, '..', '..');
const file = OMNIVOICE_DATA.files.find(item => item.path === 'omnivoice-main-kv-fp16-b1.onnx_data');
assert(file, 'Missing pinned OmniVoice weights');
const input = await open(path.join(root, '.cache/engine-models', OMNIVOICE_DATA.modelId, file.path));
const chunkBytes = 16 * 1024 * 1024, buffer = Buffer.allocUnsafe(chunkBytes), hashes = [], full = createHash('sha256');
try {
  assert.equal((await input.stat()).size, file.bytes, 'Model size differs from its original pin');
  for (let position = 0; position < file.bytes; position += chunkBytes) {
    const length = Math.min(chunkBytes, file.bytes - position);
    let offset = 0;
    while (offset < length) {
      const { bytesRead } = await input.read(buffer, offset, length - offset, position + offset);
      assert(bytesRead > 0, 'Unexpected end of pinned model'); offset += bytesRead;
    }
    const part = buffer.subarray(0, length);
    full.update(part); hashes.push(createHash('sha256').update(part).digest('hex'));
  }
  assert.equal(full.digest('hex'), file.sha256, 'Model hash differs from its original pin');
} finally { await input.close(); }
const text = `// Copyright 2026 Felix Olsson. SPDX-License-Identifier: GPL-3.0-or-later
// Generated by tooling/scripts/build-omnivoice-weight-chunks.mjs after verifying the original full-file pin.
export const OMNIVOICE_WEIGHT_CHUNKS = Object.freeze(${JSON.stringify({ ...file, chunkBytes, hashes }, null, 2).replace('"hashes": [', '"hashes": Object.freeze([').replace(/\n  \]\n\}$/, '\n  ])\n}')});
`;
const output = path.join(root, 'src/tts/omnivoice/weight-chunks.js');
if (process.argv.includes('--check')) assert.equal(await readFile(output, 'utf8'), text, 'Bundled weight chunks are stale');
else await writeFile(output, text);
console.log(`Verified original model SHA-256 and ${hashes.length} ordered chunk pins.`);
