import { describe, expect, it } from 'vitest';
import {
  AUDIO_ENDED_GAP_MAX_DELAY_MS,
  AUDIO_ENDED_GAP_THRESHOLD_SECONDS,
  BROWSER_SPEECH_BOUNDARY_TIMEOUT_MS,
  DEFAULT_AUDIO_WATCHDOG_DELAY_MS,
  HIGHLIGHT_PLAN_RESYNC_DRIFT_SECONDS,
  PDF_RENDER_UNLOAD_DELAY_MS,
  PDF_VIEWER_MESSAGE_TIMEOUT_MS,
  PLAYBACK_SETTINGS_WRITE_DEBOUNCE_MS,
  SECTION_EARLY_ADVANCE_TAIL_SECONDS,
  STREAM_SYNTHESIS_TIMEOUT_MS,
  WORD_HIGHLIGHT_LEAD_SECONDS,
} from '../../src/lib/timing-config.js';

describe('shared timing configuration', () => {
  it('publishes synchronized playback and PDF timing defaults from one module', () => {
    expect(WORD_HIGHLIGHT_LEAD_SECONDS).toBe(0);
    expect(SECTION_EARLY_ADVANCE_TAIL_SECONDS).toBe(0.05);
    expect(AUDIO_ENDED_GAP_THRESHOLD_SECONDS).toBe(0.5);
    expect(AUDIO_ENDED_GAP_MAX_DELAY_MS).toBe(250);
    expect(HIGHLIGHT_PLAN_RESYNC_DRIFT_SECONDS).toBe(0.03);
    expect(DEFAULT_AUDIO_WATCHDOG_DELAY_MS).toBe(65000);
    expect(STREAM_SYNTHESIS_TIMEOUT_MS).toBe(2500);
    expect(PDF_VIEWER_MESSAGE_TIMEOUT_MS).toBe(8000);
    expect(PDF_RENDER_UNLOAD_DELAY_MS).toBe(500);
    expect(BROWSER_SPEECH_BOUNDARY_TIMEOUT_MS).toBe(250);
    expect(PLAYBACK_SETTINGS_WRITE_DEBOUNCE_MS).toBe(150);
  });
});
