import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const [inputPath, outputPath] = process.argv.slice(2);
if (!inputPath || !outputPath || inputPath===outputPath) throw new Error('Usage: node scripts/build-ocr-recognizer.mjs ORIGINAL.onnx OUTPUT.onnx');
const require=createRequire(import.meta.url);
const {onnx}=require('../node_modules/onnxruntime-web/lib/onnxjs/ort-schema/protobuf/onnx.js');
const inputBytes=await readFile(inputPath);
if(createHash('sha256').update(inputBytes).digest('hex')!=='5435fd747c9e0efe15a96d0b378d5bd157e9492ed8fd80edf08f30d02fa24634')throw new Error('Unexpected original recognizer hash');
const model=onnx.ModelProto.decode(inputBytes),input=model.graph.output[0].name;
const int=(name,i)=>({name,type:2,i});
model.graph.node.push(onnx.NodeProto.create({name:'ocr_labels',opType:'ArgMax',input:[input],output:['ocr_labels'],attribute:[int('axis',2),int('keepdims',0)]}));
model.graph.node.push(onnx.NodeProto.create({name:'ocr_scores',opType:'ReduceMax',input:[input],output:['ocr_scores'],attribute:[{name:'axes',type:7,ints:[2]},int('keepdims',0)]}));
model.graph.output=[['ocr_labels',7],['ocr_scores',1]].map(([name,elemType])=>onnx.ValueInfoProto.create({name,type:{tensorType:{elemType,shape:{dim:[{dimParam:'batch'},{dimParam:'steps'}]}}}}));
const alphabet=JSON.parse(await readFile('public/assets/ocr/small-rec-alphabet.json'));
const space=alphabet.indexOf(' ');
if(space!==18709)throw new Error('Unexpected recognizer alphabet');
model.graph.initializer.push(onnx.TensorProto.create({name:'diagnostic_space_index',dataType:7,dims:[],int64Data:[space]}));
model.graph.node.push(onnx.NodeProto.create({name:'ocr_spaces',opType:'Gather',input:[input,'diagnostic_space_index'],output:['ocr_spaces'],attribute:[int('axis',2)]}));
model.graph.output.push(onnx.ValueInfoProto.create({name:'ocr_spaces',type:{tensorType:{elemType:1,shape:{dim:[{dimParam:'batch'},{dimParam:'steps'}]}}}}));
const bytes=onnx.ModelProto.encode(model).finish();
await writeFile(outputPath,bytes);
console.log(JSON.stringify({bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')}));
