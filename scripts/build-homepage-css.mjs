import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { chromium } from '@playwright/test';

// PostCSS is already installed by Vite in this repository's npm lockfile.
const postcss = createRequire(import.meta.url)('postcss');
export const SOURCE_CSS = '/assets/site-1.0.7.1.css';
export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const sha256 = (text) => createHash('sha256').update(text).digest('hex');

export function browserOptions() {
  return {
    headless: true,
    ...(process.env.CHROMIUM_EXECUTABLE_PATH
      ? { executablePath: process.env.CHROMIUM_EXECUTABLE_PATH } : {}),
    ...(process.env.PN_CHROMIUM_NO_SANDBOX === '1' ? { args: ['--no-sandbox'] } : {}),
  };
}

/** Keep all selectors whose matching could depend on unsupported syntax/state. */
export function matchingSelectorsInDocument(selectors) {
  return selectors.map((selector) => {
    // Functional pseudos, attribute selectors and escapes are deliberately kept.
    if (/[()[\]\\]/.test(selector)) return true;
    const base = selector
      .replace(/::(?:before|after|selection)\b/g, '')
      .replace(/:(?:focus-visible|focus-within|hover|active|focus|visited|link|disabled|enabled)\b/g, '');
    if (/:/.test(base.replace(/:root\b/g, ''))) return true;
    try {
      return Boolean(document.querySelector(base.trim() || '*'));
    } catch {
      return true; // Unknown future syntax is never a reason to drop a rule.
    }
  });
}

function mayPrune(rule) {
  for (let parent = rule.parent; parent; parent = parent.parent) {
    if (parent.type === 'atrule' && parent.name.toLowerCase() !== 'media') return false;
  }
  return true;
}

/** Remove complete nonmatching rules only. Preserve every retained value/prefix. */
export async function makeHomepageCss(css, html, browser, { prune = true } = {}) {
  const tree = postcss.parse(css.replace(/\r\n/g, '\n'));
  if (prune) {
    const rules = [];
    tree.walkRules((rule) => { if (mayPrune(rule)) rules.push(rule); });
    const context = await browser.newContext({ serviceWorkers: 'block' });
    try {
      await context.route('**/*', (route) => route.abort());
      const page = await context.newPage();
      // Block inline scripts too. This generator is for the static marketing page.
      await page.setContent('<meta http-equiv="Content-Security-Policy" content="default-src \'none\'; style-src \'unsafe-inline\'">' + html);
      const matches = await page.evaluate(matchingSelectorsInDocument, rules.map((rule) => rule.selector));
      rules.forEach((rule, index) => { if (!matches[index]) rule.remove(); });
    } finally {
      await context.close();
    }
  }
  tree.walkComments((comment) => { if (!comment.text.startsWith('!')) comment.remove(); });
  tree.walkAtRules((rule) => {
    if (rule.name.toLowerCase() === 'media' && rule.nodes?.length === 0) rule.remove();
  });
  // Only formatting metadata is minimized, never CSS values or selector syntax.
  tree.walk((node) => {
    node.raws.before = '';
    if (node.type === 'decl') node.raws.between = ':';
    if (node.type === 'rule' || node.type === 'atrule') {
      node.raws.between = '';
      node.raws.after = '';
    }
  });
  tree.raws.after = '';
  return '/* Generated by scripts/build-homepage-css.mjs; edit the shared source, not this file. */\n'
    + tree.toString() + '\n';
}

export function homepageAsset(html) {
  const links = [...html.matchAll(/<link\b[^>]*>/gi)]
    .filter(([tag]) => /\brel="stylesheet"/.test(tag));
  const assets = links.map(([tag]) => /\bhref="([^"]+)"/.exec(tag)?.[1])
    .filter((href) => href === SOURCE_CSS || /^\/assets\/home-[a-f0-9]{16}\.css$/.test(href || ''));
  if (assets.length !== 1) throw new Error('Expected one managed homepage stylesheet.');
  return assets[0];
}

export async function buildHomepageCss(root = ROOT, { check = false } = {}) {
  const publicDir = join(root, 'website/public');
  const indexPath = join(publicDir, 'index.html');
  const headersPath = join(publicDir, '_headers');
  const [html, source, headers] = await Promise.all([
    readFile(indexPath, 'utf8'), readFile(join(publicDir, SOURCE_CSS), 'utf8'),
    readFile(headersPath, 'utf8'),
  ]);
  // ponytail: static pages only; review selectors before supporting scripted markup.
  if (/<script\b|\bon[a-z]+\s*=/i.test(html)) throw new Error('Static-only CSS builder: page scripting needs manual review.');
  const previous = homepageAsset(html);
  const browser = await chromium.launch(browserOptions());
  let output;
  try { output = await makeHomepageCss(source, html, browser); }
  finally { await browser.close(); }
  const asset = `/assets/home-${sha256(output).slice(0, 16)}.css`;
  const nextHtml = html.replace(`href="${previous}"`, `href="${asset}"`);
  const begin = '# BEGIN GENERATED HOMEPAGE CSS CACHE';
  const end = '# END GENERATED HOMEPAGE CSS CACHE';
  const cacheBlock = `${begin}\n${asset}\n  Cache-Control: public, max-age=31536000, immutable\n${end}\n`;
  const marker = new RegExp(`\\n?${begin}[\\s\\S]*?${end}\\n?`);
  const nextHeaders = (headers.replace(/\r\n/g, '\n').replace(marker, '').trimEnd() + '\n\n' + cacheBlock)
    .replace(/\n/g, headers.includes('\r\n') ? '\r\n' : '\n');
  const assetPath = join(publicDir, asset);
  if (check) {
    if (html !== nextHtml || headers !== nextHeaders || await readFile(assetPath, 'utf8') !== output) {
      throw new Error('Homepage CSS, its fingerprint, or cache rule is stale. Regenerate.');
    }
  } else {
    // Do not overwrite files another process changed while the browser was running.
    if (await readFile(indexPath, 'utf8') !== html || await readFile(headersPath, 'utf8') !== headers
      || await readFile(join(publicDir, SOURCE_CSS), 'utf8') !== source) {
      throw new Error('Source changed during generation; no homepage files updated.');
    }
    await mkdir(dirname(assetPath), { recursive: true });
    try { await writeFile(assetPath, output, { flag: 'wx' }); }
    catch (error) {
      if (error.code !== 'EEXIST' || await readFile(assetPath, 'utf8') !== output) throw error;
    }
    // New asset first, then cache policy, HTML reference last. Never delete old assets.
    await writeFile(headersPath, nextHeaders);
    await writeFile(indexPath, nextHtml);
  }
  return { asset, sourceBytes: Buffer.byteLength(source.replace(/\r\n/g, '\n')), outputBytes: Buffer.byteLength(output) };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    if (process.argv.slice(2).some((arg) => arg !== '--check')) throw new Error('Usage: node scripts/build-homepage-css.mjs [--check]');
    console.log(JSON.stringify(await buildHomepageCss(ROOT, { check: process.argv.includes('--check') }), null, 2));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
